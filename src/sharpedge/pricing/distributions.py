def model_for(stat: str) -> StatModel:
    """Look up a stat's model, defaulting to a mildly overdispersed count."""
    return STAT_MODELS.get(
        stat.lower().replace(" ", "_"),
        StatModel("negbin", 1.25, True, "unrecognized stat, using a generic count"),
    )


def build(stat: str, mean: float) -> Distribution:
    """Construct a fitted distribution for a stat at a projected mean."""
    model = model_for(stat)
    mean = max(mean, 1e-6)

    if model.family == "poisson":
        return PoissonDist(mean=mean)
    if model.family == "negbin":
        return NegativeBinomialDist(mean=mean, dispersion=model.parameter)
    if model.family == "gamma":
        return GammaDist(mean=mean, cv=model.parameter)
    # Normal: the parameter scales sd with sqrt(mean), which tracks how
    # counting-stat volatility actually grows.
    return NormalDist(mean=mean, sd=max(model.parameter * math.sqrt(mean), 1e-6))


# ---------------------------------------------------------------------------
# Fitting to the market
# ---------------------------------------------------------------------------


def fit_to_market(
    stat: str, line: float, over_probability: float, tol: float = 1e-9
) -> Distribution:
    """Find the projection implied by the market's own price.

    This is the key move. Rather than projecting the player ourselves -- which
    would mean competing with the book's model using worse data -- we take the
    book's anchor price as truth about the *center* of the distribution and
    supply only the *shape*. The shape is stable and empirical; the projection
    is the hard part, and the market has already done it.

    Everything derived from here is therefore a statement about internal
    consistency, not a competing forecast: given that you priced 6.5 at this
    number, your own 8.5 is wrong.
    """
    p = min(max(over_probability, 1e-6), 1.0 - 1e-6)

    lo, hi = 1e-4, max(line * 6.0, 10.0)
    for _ in range(200):
        mid = 0.5 * (lo + hi)
        if build(stat, mid).sf(line) < p:
            lo = mid
        else:
            hi = mid
        if hi - lo < tol:
            break
    return build(stat, 0.5 * (lo + hi))


def ladder(dist: Distribution, lines: list[float]) -> dict[float, float]:
    """Fair over-probability at every line in a ladder."""
    return {line: min(max(dist.sf(line), 1e-6), 1.0 - 1e-6) for line in lines}


def standard_ladder(anchor: float, stat: str, spread: int = 4) -> list[float]:
    """Generate the alternate lines a book typically posts around an anchor."""
    model = model_for(stat)
    if model.integer:
        step = 1.0
    else:
        # Yardage props ladder in fives or tens depending on magnitude.
        step = 10.0 if anchor >= 60 else 5.0
    base = anchor
    return [
        round(base + i * step, 1)
        for i in range(-spread, spread + 1)
        if base + i * step > 0
    ]


def push_probability(dist: Distribution, line: float, stat: str) -> float:
    """Probability of landing exactly on a whole-number prop line.

    Matters because books post whole-number prop lines ("over 6 strikeouts")
    where a 6 refunds the bet. A push is not a loss, and pricing it as one
    materially understates the value of the over.
    """
    if not model_for(stat).integer:
        return 0.0
    if abs(line - round(line)) > 1e-9:
        return 0.0
    return dist.pmf(int(round(line)))
